/** Cell is 6×9 px (5×7 glyph + 1px spacing, 1px top/bottom). */
export const CELL_W = 6, CELL_H = 9;

/** Rasterise (multi-line) text into a nearest-filtered RGBA8 texture; alpha = ink. */
export function rasterText(text: string): RawTex {
  const lines = text.toUpperCase().split('\n');
  const cols = Math.max(1, ...lines.map((l) => [...l].length));
  const w = cols * CELL_W + 1, h = lines.length * CELL_H;
  const data = new Uint8Array(w * h * 4);
  lines.forEach((line, li) => {
    [...line].forEach((ch, ci) => {
      const g = G[ch] ?? G['?'];
      for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) {
        if (!(g[r] & (1 << (4 - c)))) continue;
        const x = ci * CELL_W + c + 1, y = li * CELL_H + r + 1;
        const i = (y * w + x) * 4;
        data[i] = data[i + 1] = data[i + 2] = data[i + 3] = 255;
      }
    });
  });
  return { width: w, height: h, data, filter: 'nearest' };
}
